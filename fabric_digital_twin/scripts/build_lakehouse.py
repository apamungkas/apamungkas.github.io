"""Create notebook nb_dt_seed_assets in ws_demo_digital_twin and run it to seed typed Delta tables in lh_dt_factory."""
import json
import os
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from fabric_api import b64, call, find_item, ids  # noqa: E402

SK = "spark-cli"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MD = json.load(open(os.path.join(ROOT, "data", "master_data.json"), encoding="utf-8"))


def cell_md(text):
    lines = text.strip("\n").split("\n")
    return {"cell_type": "markdown", "metadata": {}, "source": [l + "\n" for l in lines[:-1]] + [lines[-1]]}


def cell_code(code):
    lines = code.strip("\n").split("\n")
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [],
            "source": [l + "\n" for l in lines[:-1]] + [lines[-1]]}


def build_notebook(ws_id, lh_id):
    payload = {k: MD[k] for k in ("sites", "lines", "machines", "work_orders")}
    data_cell = "# Master data for PT Nusantara Manufaktur (generated by scripts/gen_master_data.py)\nimport json\nMASTER = json.loads(r'''" + json.dumps(payload, indent=1) + "''')\nprint({k: len(v) for k, v in MASTER.items()})"
    code = r'''
from datetime import date, datetime
from pyspark.sql.types import (StructType, StructField, StringType, DoubleType, IntegerType, DateType, TimestampType)

def ts(v):
    return None if v in (None, "") else datetime.fromisoformat(v.replace("Z", "+00:00")).replace(tzinfo=None)

schemas = {
    "dim_site": StructType([StructField(c, t) for c, t in [
        ("SiteId", StringType()), ("SiteName", StringType()), ("Area", StringType()), ("City", StringType()),
        ("Province", StringType()), ("Country", StringType()), ("Latitude", DoubleType()), ("Longitude", DoubleType()),
        ("Timezone", StringType()), ("PlantManager", StringType()), ("Employees", IntegerType()), ("OpenedYear", IntegerType())]]),
    "dim_production_line": StructType([StructField(c, t) for c, t in [
        ("LineId", StringType()), ("SiteId", StringType()), ("LineName", StringType()), ("LineType", StringType()),
        ("TargetUnitsPerHour", IntegerType())]]),
    "dim_machine": StructType([StructField(c, t) for c, t in [
        ("MachineId", StringType()), ("MachineName", StringType()), ("MachineType", StringType()), ("LineId", StringType()),
        ("SiteId", StringType()), ("Manufacturer", StringType()), ("Model", StringType()), ("SerialNumber", StringType()),
        ("InstallDate", DateType()), ("RatedPowerKw", DoubleType()), ("NominalRpm", DoubleType()), ("TempMaxC", DoubleType()),
        ("VibMaxMmS", DoubleType()), ("Criticality", StringType())]]),
    "maintenance_work_order": StructType([StructField(c, t) for c, t in [
        ("WorkOrderId", StringType()), ("MachineId", StringType()), ("WorkOrderType", StringType()), ("Priority", StringType()),
        ("Status", StringType()), ("Description", StringType()), ("OpenedAt", TimestampType()), ("ClosedAt", TimestampType()),
        ("Technician", StringType()), ("DowntimeMinutes", IntegerType()), ("CostIdr", DoubleType())]]),
}
converters = {
    "dim_site": lambda r: (r["SiteId"], r["SiteName"], r["Area"], r["City"], r["Province"], r["Country"], float(r["Latitude"]),
                           float(r["Longitude"]), r["Timezone"], r["PlantManager"], int(r["Employees"]), int(r["OpenedYear"])),
    "dim_production_line": lambda r: (r["LineId"], r["SiteId"], r["LineName"], r["LineType"], int(r["TargetUnitsPerHour"])),
    "dim_machine": lambda r: (r["MachineId"], r["MachineName"], r["MachineType"], r["LineId"], r["SiteId"], r["Manufacturer"],
                              r["Model"], r["SerialNumber"], date.fromisoformat(r["InstallDate"]), float(r["RatedPowerKw"]),
                              float(r["NominalRpm"]), float(r["TempMaxC"]), float(r["VibMaxMmS"]), r["Criticality"]),
    "maintenance_work_order": lambda r: (r["WorkOrderId"], r["MachineId"], r["WorkOrderType"], r["Priority"], r["Status"],
                                         r["Description"], ts(r["OpenedAt"]), ts(r["ClosedAt"]), r["Technician"],
                                         int(r["DowntimeMinutes"]), float(r["CostIdr"])),
}
sources = {"dim_site": "sites", "dim_production_line": "lines", "dim_machine": "machines", "maintenance_work_order": "work_orders"}

for table, key in sources.items():
    df = spark.createDataFrame([converters[table](r) for r in MASTER[key]], schemas[table])
    df.write.mode("overwrite").format("delta").option("overwriteSchema", "true").saveAsTable(table)
    print(f"{table}: {df.count()} rows")
'''
    check = '''
for t in ["dim_site", "dim_production_line", "dim_machine", "maintenance_work_order"]:
    print(t, spark.table(t).count())
display(spark.sql("SELECT m.MachineId, m.MachineName, l.LineName, s.SiteName FROM dim_machine m JOIN dim_production_line l ON m.LineId = l.LineId JOIN dim_site s ON l.SiteId = s.SiteId ORDER BY m.MachineId"))
'''
    nb = {
        "nbformat": 4, "nbformat_minor": 5,
        "metadata": {
            "kernel_info": {"name": "synapse_pyspark"},
            "kernelspec": {"name": "synapse_pyspark", "display_name": "Synapse PySpark", "language": "Python"},
            "language_info": {"name": "python"},
            "microsoft": {"language": "python", "language_group": "synapse_pyspark"},
            "dependencies": {"lakehouse": {"default_lakehouse": lh_id, "default_lakehouse_name": "lh_dt_factory",
                                           "default_lakehouse_workspace_id": ws_id, "known_lakehouses": [{"id": lh_id}]}},
        },
        "cells": [
            cell_md("# Digital Twin demo - seed asset master data\n"
                    "Creates the typed Delta tables used by the **ont_dt_factory** ontology and the **dtb_dt_factory** digital twin:\n"
                    "`dim_site`, `dim_production_line`, `dim_machine`, `maintenance_work_order` for PT Nusantara Manufaktur "
                    "(Cikarang, Karawang, Surabaya). Re-run any time to reset the master data."),
            cell_code(data_cell),
            cell_code(code),
            cell_code(check),
        ],
    }
    return nb


def main():
    I = ids()
    ws, lh = I["workspaceId"], I["lakehouseId"]
    nb = build_notebook(ws, lh)
    definition = {"format": "ipynb", "parts": [{"path": "notebook-content.ipynb", "payload": b64(json.dumps(nb)), "payloadType": "InlineBase64"}]}
    item = find_item(ws, "Notebook", "nb_dt_seed_assets", SK)
    if item:
        call("POST", f"workspaces/{ws}/notebooks/{item['id']}/updateDefinition", SK, body={"definition": definition})
        print("notebook updated", item["id"])
    else:
        item = call("POST", f"workspaces/{ws}/notebooks", SK, body={"displayName": "nb_dt_seed_assets",
                    "description": "Seeds typed Delta master-data tables for the digital twin demo", "definition": definition})
        if "id" not in item:
            item = find_item(ws, "Notebook", "nb_dt_seed_assets", SK)
        print("notebook created", item["id"])
    ids({"notebookId": item["id"]})
    recent = call("GET", f"workspaces/{ws}/items/{item['id']}/jobs/instances", SK).get("value", [])
    active = [j for j in recent if j.get("status") in ("NotStarted", "InProgress")]
    if active:
        print("monitoring existing job", active[0]["id"])
        loc = f"workspaces/{ws}/items/{item['id']}/jobs/instances/{active[0]['id']}"
    else:
        r = call("POST", f"workspaces/{ws}/items/{item['id']}/jobs/instances?jobType=RunNotebook", SK, lro=False)
        loc = r.get("_location")
        print("job submitted", loc)
    t0 = time.time()
    while True:
        time.sleep(15)
        st = call("GET", loc, SK, lro=False)
        print(f"[{int(time.time() - t0)}s] {st.get('status')}")
        if st.get("status") in ("Completed", "Failed", "Cancelled", "Deduped"):
            if st.get("status") != "Completed":
                print(json.dumps(st.get("failureReason"), indent=1))
            break
        if time.time() - t0 > 1800:
            print("timeout waiting for notebook")
            break
    tables = call("GET", f"workspaces/{ws}/lakehouses/{lh}/tables", SK).get("data", [])
    print("tables:", [(t["name"], t.get("format")) for t in tables])


if __name__ == "__main__":
    main()
